// Generate public/dashboard/index.html from the template, inlining real Lucide SVGs.
const fs = require('fs');
const path = require('path');

const ICONS = JSON.parse(fs.readFileSync('lucide-icons.json', 'utf8'));
const TEMPLATE = 'dashboard.template.html';
const OUT = 'public/dashboard/index.html';

function icon(name, size) {
  const def = ICONS[name];
  if (!def) throw new Error('missing icon: ' + name);
  const s = size || 24;
  return (
    `<svg class="ic" width="${s}" height="${s}" viewBox="0 0 24 24" fill="none" stroke="currentColor" ` +
    `stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">` +
    def.inner +
    `</svg>`
  );
}

let html = fs.readFileSync(TEMPLATE, 'utf8');
const used = new Set();
html = html.replace(/\{\{icon:([a-z0-9-]+)(?::(\d+))?\}\}/g, (_, name, size) => {
  used.add(name);
  return icon(name, size ? Number(size) : 24);
});

const missing = [...html.matchAll(/\{\{[^}]+\}\}/g)].map((m) => m[0]);
if (missing.length) {
  console.error('unresolved placeholders:', missing.slice(0, 10));
  process.exit(1);
}

fs.writeFileSync(OUT, html, 'utf8');
console.log(`wrote ${OUT} (${html.length} bytes)`);
console.log(`icons inlined: ${used.size} -> ${[...used].sort().join(', ')}`);

// Icon module for the parts the dashboard renders at runtime
// (quick actions, services, products, notifications, search results).
const jsOut = 'public/dashboard/icons.js';
const js = '/* Lucide icon paths (MIT) â€” generated by build-dashboard.js. */\n' +
  'window.__DASH_ICONS__ = ' + JSON.stringify(ICONS, null, 2) + ';\n';
fs.writeFileSync(jsOut, js, 'utf8');
console.log(`wrote ${jsOut} (${js.length} bytes)`);

const unused = Object.keys(ICONS).filter((n) => !used.has(n));
if (unused.length) console.log(`unused in library: ${unused.join(', ')}`);

